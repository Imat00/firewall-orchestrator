CREATE FUNCTION pg_temp.assert_migration() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS ((SELECT n.node_type, n.object_key, v.config_key, v.config_value FROM device_specific_config_value v
            JOIN device_specific_config_node n ON n.id = v.node_id
        EXCEPT SELECT node_type, object_key, config_key, config_value FROM expected_values)
        UNION ALL (SELECT node_type, object_key, config_key, config_value FROM expected_values
        EXCEPT SELECT n.node_type, n.object_key, v.config_key, v.config_value FROM device_specific_config_value v
            JOIN device_specific_config_node n ON n.id = v.node_id)) THEN
        RAISE EXCEPTION 'Migrated implementation modes differ from the expected values';
    END IF;
    IF EXISTS ((SELECT n.node_type, n.object_key, p.node_type, p.object_key, n.display_name FROM device_specific_config_node n
            LEFT JOIN device_specific_config_node p ON p.id = n.parent_id
        EXCEPT SELECT * FROM expected_nodes)
        UNION ALL (SELECT * FROM expected_nodes
        EXCEPT SELECT n.node_type, n.object_key, p.node_type, p.object_key, n.display_name FROM device_specific_config_node n
            LEFT JOIN device_specific_config_node p ON p.id = n.parent_id)) THEN
        RAISE EXCEPTION 'Only the changed managements and their device types must get a node';
    END IF;
    IF EXISTS (SELECT 1 FROM config WHERE config_key = 'fwConfigChangeMgmSettings')
        OR EXISTS (SELECT 1 FROM config WHERE config_key = 'extTicketSystems') THEN
        RAISE EXCEPTION 'The old setting and the ticket system list must be removed';
    END IF;
    IF (SELECT config_values->'fwConfigChangeMgmSettings' FROM device_specific_config_backup WHERE version = '9.8.7 implementation modes')
            IS DISTINCT FROM (SELECT settings FROM original_mgm_settings)
        OR (SELECT jsonb_array_length(config_values->'values') FROM device_specific_config_backup WHERE version = '9.8.7 implementation modes')
            IS DISTINCT FROM (SELECT count(*)::integer FROM original_values) THEN
        RAISE EXCEPTION 'The old setting and the previous implementation modes must be backed up';
    END IF;
END $$;
SELECT pg_temp.assert_migration();

