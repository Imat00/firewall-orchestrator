CREATE FUNCTION pg_temp.assert_migration() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS ((SELECT n.node_type, n.object_key, v.config_key, v.config_value FROM device_specific_config_value v
            JOIN device_specific_config_node n ON n.id = v.node_id
        EXCEPT SELECT node_type, object_key, config_key, config_value FROM expected_values)
        UNION ALL (SELECT node_type, object_key, config_key, config_value FROM expected_values
        EXCEPT SELECT n.node_type, n.object_key, v.config_key, v.config_value FROM device_specific_config_value v
            JOIN device_specific_config_node n ON n.id = v.node_id)) THEN
        RAISE EXCEPTION 'Migrated SecureChange connection differs from the expected values';
    END IF;
    IF (SELECT count(*) FROM device_specific_config_node) <> 7 THEN
        RAISE EXCEPTION 'No node must be added, every management with values has one already';
    END IF;
    IF (SELECT jsonb_array_length(config_values) FROM device_specific_config_backup WHERE version = '9.8.7 securechange connection')
            IS DISTINCT FROM (SELECT selections::integer FROM original_selections) THEN
        RAISE EXCEPTION 'The previous selections must be backed up';
    END IF;
    IF EXISTS (SELECT 1 FROM config WHERE config_key = 'extTicketSystems')
        OR (SELECT jsonb_array_length(config_values) FROM device_specific_config_backup WHERE version = '9.8.7 extTicketSystems') <> 4
        OR (SELECT config_values::text FROM device_specific_config_backup WHERE version = '9.8.7 extTicketSystems') LIKE '%Authorization%' THEN
        RAISE EXCEPTION 'The ticket system list must be backed up without authorization values and removed';
    END IF;
END $$;
SELECT pg_temp.assert_migration();

