-- Test of the SecureChange connection migration of upgrade/9.9.3.sql. The test task inserts the upgrade file at the two
-- run-upgrade markers below, which also shows that the upgrade can be repeated.
-- An isolated schema and temporary tables protect the settings; the transaction is rolled back.
-- The implementation mode and request settings migrations count as done (their backups exist), so they leave the
-- settings below unchanged. This probes: a selected Tufin SecureChange system becomes tufinSecureChange, a level
-- selecting another or an unknown system loses the selection and its modes in effect for external ticket systems become
-- Manual (own and inherited ones, other modes stay), the connection of the system most managements use becomes global,
-- a management using another system gets its differing values, a system without credential leaves the credential to be
-- inherited, the selections are backed up, the ticket system list is backed up without authorization values and removed,
-- and a repeated upgrade keeps an administrator change.
\set ON_ERROR_STOP 1
BEGIN;
CREATE SCHEMA sc_connection_upgrade_9_8_7_test;
-- the other parts of the upgrade work on the real tables of the public schema
SET LOCAL search_path = sc_connection_upgrade_9_8_7_test, pg_temp, public;
