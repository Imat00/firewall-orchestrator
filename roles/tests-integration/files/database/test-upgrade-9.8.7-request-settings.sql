-- Test of the request settings migration of upgrade/9.8.7.sql. The test task inserts the upgrade file at the two
-- run-upgrade markers below, which also shows that the upgrade can be repeated.
-- An isolated schema and temporary tables protect the settings; the transaction is rolled back.
-- The implementation mode migration counts as done (its backup exists), so it leaves the settings below unchanged and
-- provides the former routing. This probes: the system most managements use (selected external ticket system in effect,
-- including an inherited one) becomes global where its values differ from the defaults, a management using another
-- system gets its differing values, a missing value counts as default, an invalid value is left out, a management routed
-- to a Check Point system gets the values of that system, disabled routes and managements without system stay unchanged,
-- unused systems do not count, the systems are backed up, and a repeated upgrade keeps an administrator change.
\set ON_ERROR_STOP 1
BEGIN;
CREATE SCHEMA request_settings_upgrade_9_8_7_test;
-- the other parts of the upgrade work on the real tables of the public schema
SET LOCAL search_path = request_settings_upgrade_9_8_7_test, pg_temp, public;
CREATE TEMP TABLE config (config_key varchar, config_value varchar, config_user integer,
    PRIMARY KEY (config_key, config_user));
